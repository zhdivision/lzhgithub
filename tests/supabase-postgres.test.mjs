import assert from 'node:assert/strict';
import fs from 'node:fs';
import { PGlite } from '@electric-sql/pglite';

const root = new URL('../', import.meta.url);
const database = new PGlite();
await database.exec('create role anon; create role authenticated; create role service_role bypassrls;');
await database.exec(fs.readFileSync(new URL('supabase/migrations/20261027150840_cup_shared_scores.sql', root), 'utf8'));
const seed = fs.readFileSync(new URL('supabase/seed.sql', root), 'utf8');
await database.exec(seed);
await database.exec(seed); // Import must be safe to repeat.
await database.exec('set role service_role;');
const snapshot = (await database.query('select public.cup_snapshot() as value')).rows[0].value;
assert.equal(snapshot.teams.length, 23); assert.equal(snapshot.matches.length, 33);
const previous = snapshot.matches.find(value => value.id === 'E-12');
const oldHistory = (await database.query('select id from public.cup_history where entity_id=$1', ['E-12'])).rows.map(row => row.id);
const patch = { homeScore: 2, awayScore: 0, status: 'finished', round: 3, kickoff: null, home: 'A1' };
const update = async (version, value) => (await database.query('select public.cup_update_entity($1,$2,$3,$4::jsonb) as value', ['match','E-12',version,JSON.stringify(value)])).rows[0].value;
const concurrent = await Promise.all([update(previous.version, patch), update(previous.version, patch)]);
assert.equal(concurrent.filter(value => value.status === 200).length, 1);
assert.equal(concurrent.filter(value => value.status === 409).length, 1);
const saved = concurrent.find(value => value.status === 200).value;
assert.equal(saved.home, previous.home); assert.equal(saved.version, previous.version + 1);
assert.equal(saved.demo, false);
const cancelled = await update(saved.version, { ...patch, status: 'unplayed' });
assert.equal(cancelled.value.homeScore, null); assert.equal(cancelled.value.awayScore, null);
const history = (await database.query('select * from public.cup_history where entity_id=$1 order by at', ['E-12'])).rows.filter(row => !oldHistory.includes(row.id));
assert.equal(history.length, 2); assert.deepEqual(history[0].before_data, previous);
assert.equal(history[1].after_data.status, 'unplayed');
for (let n = 1; n <= 11; n++) assert.equal((await database.query('select public.cup_login_attempt($1) as n',['hashed-ip'])).rows[0].n, n);
await database.query("update public.cup_login_attempts set until_at=now()-interval '1 minute'");
assert.equal((await database.query('select public.cup_login_attempt($1) as n',['hashed-ip'])).rows[0].n, 1);
await database.exec('reset role; set role anon;');
await assert.rejects(database.query('select * from public.cup_matches'), /permission denied/);
await assert.rejects(database.query('select public.cup_snapshot()'), /permission denied/);
await assert.rejects(database.query('select public.cup_update_entity($1,$2,$3,$4::jsonb)', ['match','E-12',1,'{}']), /permission denied/);
await database.exec('reset role;');
const security = (await database.query("select relname,relrowsecurity from pg_class where relname in ('cup_teams','cup_matches','cup_history','cup_login_attempts')")).rows;
assert.equal(security.length, 4); assert.ok(security.every(row => row.relrowsecurity));
await database.close();
console.log(JSON.stringify({ postgresChecks: 'passed', teams:23, matches:33, idempotentImport:true, versionConflicts:true, atomicAudit:true, anonymousAccessDenied:true, rls:true }));
